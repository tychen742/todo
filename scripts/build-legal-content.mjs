// Generates features/legal/legalContent.generated.ts from docs/legal/*.md so the
// markdown drafts stay the single source of truth for the /privacy and /terms pages.
// Usage: node scripts/build-legal-content.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'features/legal/legalContent.generated.ts');
const sources = {
  privacyPolicyMarkdown: 'docs/legal/privacy-policy.md',
  termsOfServiceMarkdown: 'docs/legal/terms-of-service.md',
};

// Drop the internal review note (a leading blockquote) before publishing.
function publishable(markdown) {
  return markdown
    .split('\n')
    .filter((line) => !line.startsWith('>'))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

let output = '// Generated by scripts/build-legal-content.mjs from docs/legal. Do not edit.\n';
for (const [name, path] of Object.entries(sources)) {
  const markdown = publishable(readFileSync(join(root, path), 'utf8'));
  output += `\nexport const ${name} = ${JSON.stringify(markdown)};\n`;
}

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outFile, 'utf8');
  } catch {}
  if (current !== output) {
    console.error('Legal page content is out of date. Run: npm run legal:build');
    process.exit(1);
  }
  console.log('Legal page content is up to date.');
} else {
  writeFileSync(outFile, output);
  console.log(`Wrote ${outFile}`);
}
